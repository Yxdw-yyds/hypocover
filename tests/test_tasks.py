"""Round-trip checks: every ground-truth hypothesis, rendered in the answer
format, must parse, validate and map back to its own canonical key.

Datasets are generated by scripts/make_datasets.sh; missing files are skipped.
Known upstream issue: Boolean 'full' (with NOR) contains ground-truth
expressions that the official validator rejects (depth of NOT(x OR y) counts
as 2), so for those datasets we only report the ceiling.
"""
from pathlib import Path

import pytest

from hypocover.tasks import make_task

ROOT = Path(__file__).resolve().parents[1]
CASES = [
    ("causal", "data/causal/n4.json"),
    ("causal", "data/causal/n5.json"),
    ("3d", "data/3d/tp2.json"),
    ("3d", "data/3d/tp3.json"),
    ("boolean", "data/boolean/basic_d2.json"),
    pytest.param("boolean", "data/boolean/extended_d2.json", marks=pytest.mark.xfail(
        reason="upstream: NOT(x OR y) is in H_O but the validator reads it as NOR, "
               "which 'extended' does not allow (ceiling ~0.985)", strict=True)),
]


def ceiling(task, insts):
    ok = tot = 0
    for inst in insts:
        for h in inst.gt:
            p = task.parse(task.render(h))
            tot += 1
            ok += bool(p is not None and task.is_valid(p, inst) and task.key(p) in inst.gt_keys)
    return ok / max(tot, 1)


@pytest.mark.parametrize("name,path", CASES)
def test_roundtrip(name, path):
    if not (ROOT / path).exists():
        pytest.skip(f"{path} not generated")
    task = make_task(name, str(ROOT / path))
    insts = task.sample_instances(15, seed=0, min_size=2)
    assert insts
    assert ceiling(task, insts) == 1.0


def test_mock_partition_runs():
    path = ROOT / "data/3d/tp2.json"
    if not path.exists():
        pytest.skip("data missing")
    from hypocover.llm import make_llm
    from hypocover.methods import make_method
    from hypocover.metrics import score

    task = make_task("3d", str(path))
    inst = task.sample_instances(1, seed=1, min_size=4)[0]
    llm = make_llm("mock:zipf", seed=0).bind(task, inst)
    res = make_method("partition").run(task, inst, llm, inst.size)
    assert len(res.attempts) == inst.size
    s = score(res.attempts, inst.gt_keys, inst.size)
    assert 0 <= s.rr <= 1 and s.vr > 0.5


def test_coverage_reward_shares_duplicates():
    path = ROOT / "data/3d/tp2.json"
    if not path.exists():
        pytest.skip("data missing")
    from rl.coverage_reward import score_group

    task = make_task("3d", str(path))
    inst = task.sample_instances(1, seed=0, min_size=4)[0]
    a, b, c = (task.render(h) for h in inst.gt[:3])
    hist = {str(task.key(inst.gt[2]))}
    r = score_group(task, inst, hist, [a, a, b, c, "garbage"])
    assert r == [0.5, 0.5, 1.0, 0.0, -1.0]
    assert sum(x for x in r if x > 0) == 2  # = number of distinct new valid answers
